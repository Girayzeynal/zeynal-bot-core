"""Prospective-only official club evidence screening against a frozen forecast.

No model input, coefficients, ledger writes, settlement, or retrospective
backfill. A source article can be available *now* but cannot be credited
towards a forecast issued before it was first captured. Proof of fixture,
player and time binding is explicit; empty inputs fail closed. Every result
is for a future *human-reviewed shadow experiment* only.
"""
import re

from hybrid_engine.official_club_capture import verify_article_capture

SHA256=re.compile(r"^[0-9a-f]{64}$")
LEAGUES=frozenset(("NBA","EUROLEAGUE","EUROCUP"))
MAX_AGE_SECONDS=72*3600


def _utc(d,key):
    x=d.get(key) if isinstance(d,dict) else None
    return x if type(x) is int and x>0 else None


def _ident(d,key):
    x=d.get(key) if isinstance(d,dict) else None
    return x if type(x) is str and 0<len(x)<=128 and x.strip()==x else None


def assess_against_frozen_forecast(article, *, club, frozen=None,
                                   captured=None, binding=None):
    """Fail-closed as-of, identity and source consistency audit.

    frozen = existing immutable snapshot payload *plus* archived SHA proof
        in frozen["snapshot_sha256"] (never synthesize a forecast);
        expected common keys: league, season, fixture_id, fixture_start_utc,
        prediction_generated_at_utc, home/away provider_id.
    captured = future opt-in, append-only evidence receipt with actual
        observed_at_utc, captured_at_utc, source/body SHA pins.
    binding = independent player + fixture ID mapping record (not guessed
        from a text match); not yet generated by this pilot.

    An all-green result means eligible for human SHADOW REVIEW, not an
    approved lineup status, a pre-existing prediction input, or model change.
    """
    a=article if isinstance(article,dict) else {}
    c=club if isinstance(club,dict) else {}
    f=frozen if isinstance(frozen,dict) else {}
    r=captured if isinstance(captured,dict) else {}
    b=binding if isinstance(binding,dict) else {}
    reasons=[]
    def blocked(why):
        if why not in reasons:
            reasons.append(why)
    url=_ident(a,"source_url")
    digest=_ident(a,"body_sha256")
    if (a.get("status")!="OFFICIAL_ARTICLE_OBSERVED_NOT_ROSTER_VERIFIED" or
        a.get("source_http_status")!=200 or not url or
        not digest or not SHA256.fullmatch(digest)):
        blocked("ARTICLE_SOURCE_UNVERIFIED")
    if a.get("club_key")!=c.get("club_key") or a.get("league")!=c.get("league"):
        blocked("ARTICLE_CLUB_SCOPE_CONFLICT")
    if (a.get("publication_time_status")!="PRECISE_PAGE_PUBLICATION_TIME"
        or _utc(a,"published_utc") is None):
        blocked("PRECISE_ARTICLE_PUBLICATION_CLOCK_UNVERIFIED")
    observed=_utc(a,"observed_at_utc")
    if observed is None:
        blocked("ARTICLE_OBSERVATION_CLOCK_UNVERIFIED")

    # A later reconstruction of source metadata is NEVER a pregame capture.
    first=_utc(r,"observed_at_utc")
    sealed=_utc(r,"captured_at_utc")
    try:
        verify_article_capture(r)
    except (ValueError,TypeError,KeyError,OverflowError):
        blocked("FIRST_CAPTURE_RECEIPT_HASH_OR_CLOCK_INVALID")
    if (r.get("format")!="OFFICIAL_CLUB_CAPTURE_RECEIPT_V1" or
        r.get("club_key")!=a.get("club_key") or
        r.get("source_url")!=url or r.get("body_sha256")!=digest or
        not _ident(r,"receipt_sha256") or
        not SHA256.fullmatch(r["receipt_sha256"]) or
        observed is None or first!=observed or sealed is None or
        sealed<first or sealed>first+600):
        blocked("PINNED_FIRST_CAPTURE_RECEIPT_REQUIRED")
    publication=_utc(a,"published_utc")
    if publication is not None and observed is not None and publication>observed:
        blocked("PUBLICATION_AFTER_OBSERVATION")

    # Matches the repo's independent frozen forecast contract.
    cutoff=_utc(f,"prediction_generated_at_utc")
    created=_utc(f,"created_at_utc")
    tipoff=_utc(f,"fixture_start_utc")
    if (not _ident(f,"fixture_id") or f.get("league") not in LEAGUES or
        _ident(f,"season") is None or cutoff is None or created is None or
        tipoff is None or not (cutoff<=created<tipoff) or
        not isinstance(f.get("snapshot_sha256"),str) or
        not SHA256.fullmatch(f["snapshot_sha256"])):
        blocked("FROZEN_PRETIPOFF_FORECAST_IDENTITY_OR_PIN_REQUIRED")
    if f.get("league")!=a.get("league") or f.get("season")!="2026/2027":
        blocked("FORECAST_SOURCE_SEASON_SCOPE_CONFLICT")
    fixture_id=_ident(f,"fixture_id")
    home=_ident(f.get("home"),"provider_id")
    away=_ident(f.get("away"),"provider_id")
    team=_ident(c,"native_team_id")
    if (not team or not home or not away or team not in (home,away)):
        blocked("SOURCE_TEAM_NOT_BOUND_TO_FIXTURE_SIDE")

    if (not fixture_id or b.get("fixture_id")!=fixture_id or
        b.get("league")!=f.get("league") or
        b.get("provider_team_id")!=team):
        blocked("INDEPENDENT_FIXTURE_BINDING_REQUIRED")
    if (not _ident(b,"provider_player_id") or not _ident(b,"player_name_text") or
        _ident(b,"identity_evidence_sha256") is None or
        not SHA256.fullmatch(b["identity_evidence_sha256"]) or
        not isinstance(a.get("injury_absence_claim_candidates"),list) or
        b["player_name_text"] not in {
            x.get("player_name_text") for x in
            a.get("injury_absence_claim_candidates",[])
            if isinstance(x,dict)}):
        blocked("INDEPENDENT_PLAYER_ROSTER_BINDING_REQUIRED")

    # Check as-of using FIRST ACTUAL OBSERVATION, not an earlier displayed
    # article date or a later after-the-fact downloaded PDF.
    if cutoff is not None:
        if observed is None or sealed is None or observed>cutoff or sealed>cutoff:
            blocked("ARTICLE_EVIDENCE_CAPTURED_AFTER_FROZEN_FORECAST")
        if publication is None or publication>cutoff:
            blocked("ARTICLE_PUBLICATION_NOT_PRE_FORECAST")
    if tipoff is not None:
        if observed is None or sealed is None or observed>=tipoff or sealed>=tipoff:
            blocked("ARTICLE_EVIDENCE_NOT_PRE_TIPOFF")
        if publication is None or publication>=tipoff:
            blocked("ARTICLE_PUBLICATION_NOT_PRE_TIPOFF")
        if publication is not None and tipoff-publication>MAX_AGE_SECONDS:
            blocked("ARTICLE_OLDER_THAN_72H_FOR_FIXTURE")
    return dict(format="OFFICIAL_CLUB_FROZEN_ASOF_SCREEN_V1",
                status=("SHADOW_REVIEW_ONLY" if not reasons else "ABSTAIN"),
                reasons=reasons,
                fixture_id=fixture_id,
                article_url=url,club_key=c.get("club_key"),
                preforecast_captured=not any(x in reasons for x in (
                    "PINNED_FIRST_CAPTURE_RECEIPT_REQUIRED",
                    "FIRST_CAPTURE_RECEIPT_HASH_OR_CLOCK_INVALID",
                    "ARTICLE_OBSERVATION_CLOCK_UNVERIFIED",
                    "ARTICLE_EVIDENCE_CAPTURED_AFTER_FROZEN_FORECAST")),
                human_shadow_review_eligible=not reasons,
                model_input=False,forecast_changed=False,
                production_changed=False, historical_forecast_modified=False)
